import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceRoot = join(root, "src");
const configPath = join(root, "public", "config.json");
const output = join(sourceRoot, "generated", "mdi-icons.ts");

function files(path) {
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const child = join(path, entry.name);
    return entry.isDirectory() ? files(child) : [child];
  });
}

const content = [...files(sourceRoot).filter((path) => [".ts", ".tsx"].includes(extname(path))), configPath]
  .filter((path) => !path.endsWith("mdi-icons.ts"))
  .map((path) => readFileSync(path, "utf8"))
  .join("\n");
const ids = [...new Set(content.match(/mdi:[a-z0-9-]+/g) || [])].sort();
const exportName = (id) => id === "mdi:home-rounded"
  ? "mdiHome"
  : `mdi${id.slice(4).split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
const names = [...new Set(ids.map(exportName))].sort();

mkdirSync(join(sourceRoot, "generated"), { recursive: true });
writeFileSync(output, `// Generated by scripts/generate-mdi-icons.mjs. Do not edit.\nimport { ${names.join(", ")} } from "@mdi/js";\n\nexport const mdiIcons: Record<string, string> = {\n${ids.map((id) => `  ${JSON.stringify(id)}: ${exportName(id)}`).join(",\n")}\n};\n`, "utf8");
console.log(`Generated ${ids.length} browser-native SVG icons`);
